"""Original pixel art. Pillow is authoring-only; runtime serves embedded GIF bytes.

The break pose is a review concept, never selected by runtime timer state.
Preview digits are illustrative, not a reproduction of Divoom's native font.
"""
from pathlib import Path
import base64
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
COLORS = ['#FF00FF', '#0C151F', '#182838', '#283D4D', '#F6D6A0',
          '#D8A66D', '#AB754F', '#FFEAC4', '#E5A5A0', '#75BDB5',
          '#A6E0CF', '#456D73', '#BC8C78', '#785B59', '#D0D9DF']

def scene(rest=False):
    im = Image.new('P', (64, 64), 1)
    palette = [v for c in COLORS for v in bytes.fromhex(c[1:])]
    im.putpalette(palette + [0] * (768-len(palette)))
    d = ImageDraw.Draw(im)
    def r(box, color): d.rectangle(box, fill=color)
    # Quiet floor shadow; no headings, decoration text, or progress indicator.
    r((12, 49, 53, 50), 2)
    if not rest:
        # Tail curling beside the chair.
        d.line([(21,40),(15,40),(12,37),(12,33),(14,31)], fill=6, width=5)
        d.line([(21,39),(16,39),(14,37),(14,34)], fill=4, width=3)
        # Body and cheek silhouette, hand-placed on a 64px grid.
        d.polygon([(21,30),(36,30),(40,36),(40,43),(19,43),(18,36)], fill=6)
        r((21,32,36,41),4); r((25,33,33,39),7)
        d.polygon([(17,22),(17,11),(20,11),(25,16),(34,16),(39,11),
                   (42,11),(42,23),(44,25),(44,31),(41,35),(20,35),
                   (16,31),(16,25)], fill=6)
        d.polygon([(19,23),(19,14),(24,19),(35,19),(40,14),(40,24),
                   (42,26),(42,30),(39,33),(21,33),(18,30),(18,26)], fill=4)
        d.polygon([(20,16),(20,21),(24,21)],fill=8)
        d.polygon([(39,16),(35,21),(39,21)],fill=8)
        r((27,18,29,21),5); r((31,18,33,20),5)
        r((21,25,23,28),1);r((35,25,37,28),1)
        r((22,25,22,25),7);r((36,25,36,25),7)
        r((20,29,23,30),8);r((36,29,39,30),8)
        r((28,28,30,29),6);r((29,30,29,31),6)
        # Small wood desk and laptop; cat remains the dominant shape.
        r((16,42,51,44),6);r((15,40,52,42),12)
        r((18,44,20,49),13);r((47,44,49,49),13)
        r((31,31,48,39),11);r((33,32,47,37),9)
        r((35,33,45,34),10);r((33,39,49,40),3)
        r((24,38,29,39),7);r((25,40,29,40),5)
        # Tiny mug at the edge of the desk.
        r((18,36,22,39),8);r((23,37,24,38),12)
    else:
        # Curled-up companion on a cushion. Review-only pose.
        r((16,44,49,47),11);r((13,42,52,44),9);r((17,40,48,42),10)
        d.ellipse((18,24,48,44),fill=6)
        d.ellipse((20,25,46,42),fill=4)
        d.ellipse((29,29,44,40),fill=5)
        d.polygon([(17,31),(17,23),(20,23),(24,27),(30,27),(34,23),
                   (36,23),(36,34),(33,38),(20,38),(16,35)],fill=6)
        d.polygon([(19,31),(19,26),(23,30),(30,30),(34,26),(34,34),
                   (31,36),(21,36),(18,34)],fill=4)
        d.line((20,32,23,33,25,32),fill=1,width=1)
        d.line((28,32,30,33,32,32),fill=1,width=1)
        r((25,34,27,34),8)
        d.line([(45,32),(47,36),(45,40),(40,43),(32,43),(28,41)],fill=6,width=5)
        d.line([(44,33),(45,36),(43,39),(39,41),(33,41)],fill=7,width=3)
    # Bottom band (y=106..121 at native resolution) is reserved for native text.
    assert 0 not in im.tobytes()
    return im.resize((128,128),Image.Resampling.NEAREST)

DIGITS = {'0':['01110','10001','10011','10101','11001','10001','01110'],
          '2':['01110','10001','00001','00010','00100','01000','11111'],
          '5':['11111','10000','11110','00001','00001','10001','01110'],
          ':':['0','1','1','0','1','1','0']}
def preview(im, text):
    out=im.convert('RGB');d=ImageDraw.Draw(out)
    x=(128-sum(len(DIGITS[c][0])+2 for c in text)+2)//2
    for c in text:
        for y,row in enumerate(DIGITS[c]):
            for dx,pixel in enumerate(row):
                if pixel=='1':d.point((x+dx,108+y),fill=COLORS[14])
        x+=len(DIGITS[c][0])+2
    return out

if __name__ == '__main__':
    focus=scene();rest=scene(True)
    path=ROOT/'assets/pomodoro-cat-v2.gif'
    focus.save(path,optimize=False)
    (ROOT/'src/pomodoro-cat-background.ts').write_text(
        '// Original static cat artwork. Generated by scripts/build-pomodoro-cat.py.\n'
        '// Single opaque frame; unused palette index 0. No phase-driven reload.\n'
        "export const POMODORO_CAT_BACKGROUND=Buffer.from('"+
        base64.b64encode(path.read_bytes()).decode()+"','base64');\n",encoding='utf8')
    for name,art,time in [('focus',focus,'25:00'),('break-concept',rest,'05:00')]:
        image=preview(art,time)
        image.save(ROOT/f'assets/pomodoro-cat-{name}-128.png')
        image.resize((512,512),Image.Resampling.NEAREST).save(ROOT/f'assets/pomodoro-cat-{name}-512.png')
    # Keep the unused break background as a design source, not a server endpoint.
    rest.save(ROOT/'assets/pomodoro-cat-break-concept.gif',optimize=False)
    with Image.open(path) as check:
        assert check.size==(128,128) and check.n_frames==1
        assert 0 not in check.tobytes() and 'transparency' not in check.info
