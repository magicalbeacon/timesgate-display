"""Author the original sleeping-cat loop; Pillow 12.3.0 is authoring-only.

Run normally to write/validate, or with --check for read-only validation. The
existing static and typing assets are never written. Preview 05:00 is illustrative;
this background has no phase logic, timer digits, device calls, or runtime decoder.
The size/frame/duration budgets are engineering constraints, not firmware proof.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
from io import BytesIO
from pathlib import Path
import re
import runpy

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
TYPING = runpy.run_path(str(ROOT / 'scripts/build-pomodoro-cat-animation.py'))
STATIC = TYPING['STATIC']
COLORS = STATIC['COLORS']
parse_gif = TYPING['parse_gif']
encode_full_frames = TYPING['encode_full_frames']
DURATIONS_MS = (900, 600, 120, 480, 500, 1000)
LABELS = ('Rest', 'Breathe in', 'Ear twitch', 'Breath held', 'Settle', 'Rest')
GIF_PATH = 'assets/pomodoro-cat-sleep-v1.gif'
MODULE_PATH = 'src/pomodoro-cat-sleep-animation.ts'
PREVIEW_128 = 'assets/pomodoro-cat-sleep-preview-128.gif'
PREVIEW_512 = 'assets/pomodoro-cat-sleep-preview-512.gif'
CONTACT_SHEET = 'assets/pomodoro-cat-sleep-contact-sheet.png'
PRESERVED_PATHS = (*TYPING['STATIC_PATHS'], 'scripts/build-pomodoro-cat-animation.py',
    TYPING['GIF_PATH'], TYPING['MODULE_PATH'], TYPING['PREVIEW_128'],
    TYPING['PREVIEW_512'], TYPING['CONTACT_SHEET'])


def preserved_snapshot():
    return {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in PRESERVED_PATHS}


def sleep_scene(inhale=False, twitch=False):
    """The existing original curled-cat art, with a one-grid-pixel breath/twitch."""
    im = Image.new('P', (64, 64), 1)
    im.putpalette(STATIC['scene'](True).getpalette())
    d = ImageDraw.Draw(im)
    def r(box, color): d.rectangle(box, fill=color)
    lift = int(inhale)
    # Same stationary floor/cushion as the original break concept.
    r((12, 49, 53, 50), 2)
    r((16, 44, 49, 47), 11)
    r((13, 42, 52, 44), 9)
    r((17, 40, 48, 42), 10)
    # Only the upper back rises gently; the sleeping face and curled tail stay put.
    d.ellipse((18, 24-lift, 48, 44), fill=6)
    d.ellipse((20, 25-lift, 46, 42), fill=4)
    d.ellipse((29, 29-lift, 44, 40), fill=5)
    ear_x, ear_y = (35, 22) if twitch else (34, 23)
    d.polygon([(17, 31), (17, 23), (20, 23), (24, 27), (30, 27),
               (ear_x, ear_y), (36, 23), (36, 34), (33, 38), (20, 38), (16, 35)], fill=6)
    d.polygon([(19, 31), (19, 26), (23, 30), (30, 30), (34, 26),
               (34, 34), (31, 36), (21, 36), (18, 34)], fill=4)
    d.line((20, 32, 23, 33, 25, 32), fill=1, width=1)
    d.line((28, 32, 30, 33, 32, 32), fill=1, width=1)
    r((25, 34, 27, 34), 8)
    d.line([(45, 32), (47, 36), (45, 40), (40, 43), (32, 43), (28, 41)], fill=6, width=5)
    d.line([(44, 33), (45, 36), (43, 39), (39, 41), (33, 41)], fill=7, width=3)
    return im.resize((128, 128), Image.Resampling.NEAREST)


def animation_frames():
    return [sleep_scene(inhale, twitch) for inhale, twitch in
            ((False, False), (True, False), (True, True),
             (True, False), (False, False), (False, False))]


def overlay_time(frame):
    im = frame.copy()
    d = ImageDraw.Draw(im)
    digits = STATIC['DIGITS']
    text = '05:00'
    x = (128-sum(len(digits[c][0])+2 for c in text)+2)//2
    for c in text:
        for y, row in enumerate(digits[c]):
            for dx, pixel in enumerate(row):
                if pixel == '1': d.point((x+dx, 108+y), fill=14)
        x += len(digits[c][0])+2
    return im


def contact_sheet(frames):
    sheet = Image.new('RGB', (840, 652), COLORS[1])
    d = ImageDraw.Draw(sheet)
    d.text((12, 10), 'Original sleeping-cat loop | 05:00 is illustrative | 3.60 s loop', fill=COLORS[14])
    for i, frame in enumerate(frames):
        x, y = (i%3)*280+12, (i//3)*304+40
        sheet.paste(frame.convert('RGB').resize((256, 256), Image.Resampling.NEAREST), (x, y))
        d.text((x, y+264), f'{i+1}. {LABELS[i]} | {DURATIONS_MS[i]} ms', fill=COLORS[14])
    stream = BytesIO()
    sheet.save(stream, format='PNG')
    return stream.getvalue()


def build_outputs():
    frames = animation_frames()
    gif = encode_full_frames(frames, DURATIONS_MS)
    previews = [overlay_time(frame) for frame in frames]
    module = (
        '// Original sleeping-cat artwork. Generated by scripts/build-pomodoro-cat-sleep-animation.py.\n'
        '// Six opaque full-canvas frames; one global palette; index 0 unused; loops forever.\n'
        '// 128 x 128; durations 900/600/120/480/500/1000 ms; total 3600 ms.\n'
        '// Manually selected art only: no phase logic or drawn countdown. Footer stays clear.\n'
        '// Authoring budgets are engineering constraints, not firmware-compatibility proof.\n'
        "export const POMODORO_CAT_SLEEP_ANIMATION=Buffer.from('" +
        base64.b64encode(gif).decode('ascii') + "','base64');\n"
    ).encode('utf8')
    return {
        GIF_PATH: gif, MODULE_PATH: module,
        PREVIEW_128: encode_full_frames(previews, DURATIONS_MS),
        PREVIEW_512: encode_full_frames([
            frame.resize((512, 512), Image.Resampling.NEAREST) for frame in previews
        ], DURATIONS_MS), CONTACT_SHEET: contact_sheet(previews),
    }


def validate_gif(data, expected_frames, size, production=False):
    parsed = parse_gif(data)
    assert data[:6] == b'GIF89a'
    assert parsed['size'] == size and parsed['loop'] == 0
    assert len(parsed['frames']) == len(DURATIONS_MS) == 6
    palette = bytes(v for c in COLORS for v in bytes.fromhex(c[1:]))
    palette += b'\x00'*(768-len(palette))
    assert parsed['palette'] == palette
    assert parsed['palette'][:3] == b'\xff\x00\xff'
    if production:
        assert 4 <= len(parsed['frames']) <= 8
        assert len(data) <= 32768 and 1000 <= sum(DURATIONS_MS) <= 5000
    durations = []
    reference = STATIC['scene'](True)
    with Image.open(BytesIO(data)) as decoded:
        assert decoded.n_frames == 6 and decoded.info.get('loop') == 0
        assert 'transparency' not in decoded.info
        for i, record in enumerate(parsed['frames']):
            assert record['box'] == (0, 0, *size) and not record['local_palette']
            control = record['control']
            assert control and control['flags'] == 4 and not control['transparency']
            assert control['disposal'] == 1
            durations.append(control['duration'])
            decoded.seek(i)
            decoded.load()
            assert decoded.size == size and decoded.info['duration'] == DURATIONS_MS[i]
            assert 'transparency' not in decoded.info
            assert decoded.convert('RGB').tobytes() == expected_frames[i].convert('RGB').tobytes()
            assert decoded.convert('RGBA').getchannel('A').getextrema() == (255, 255)
            standalone = parsed['header'] + record['record'] + b'\x3b'
            with Image.open(BytesIO(standalone)) as indexed:
                indexed.load()
                assert indexed.mode == 'P' and 0 not in indexed.tobytes()
                if production:
                    assert indexed.crop((0, 108, 128, 124)).tobytes() == bytes([1])*(128*16)
                    for y in range(128):
                        for x in range(128):
                            # Upper back + ear only; cushion, floor, footer and backdrop stay fixed.
                            moving = 48 <= x < 98 and 44 <= y < 82
                            if not moving:
                                assert indexed.getpixel((x, y)) == reference.getpixel((x, y))
    assert tuple(durations) == DURATIONS_MS and sum(durations) == 3600


def validate_outputs(outputs):
    frames = animation_frames()
    assert frames[0].tobytes() == STATIC['scene'](True).tobytes(), 'Original break art changed'
    assert frames[-1].tobytes() == frames[0].tobytes()
    assert len({f.tobytes() for f in frames}) == 3
    validate_gif(outputs[GIF_PATH], frames, (128, 128), production=True)
    previews = [overlay_time(frame) for frame in frames]
    validate_gif(outputs[PREVIEW_128], previews, (128, 128))
    validate_gif(outputs[PREVIEW_512], [
        f.resize((512, 512), Image.Resampling.NEAREST) for f in previews
    ], (512, 512))
    match = re.search(rb"POMODORO_CAT_SLEEP_ANIMATION=Buffer\.from\('([A-Za-z0-9+/=]+)','base64'\)",
                      outputs[MODULE_PATH])
    assert match and base64.b64decode(match[1], validate=True) == outputs[GIF_PATH]
    with Image.open(BytesIO(outputs[CONTACT_SHEET])) as sheet:
        sheet.load()
        assert sheet.size == (840, 652) and sheet.format == 'PNG'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate artifacts without writing')
    args = parser.parse_args()
    before = preserved_snapshot()
    outputs = build_outputs()
    assert outputs == build_outputs(), 'Non-deterministic generation'
    validate_outputs(outputs)
    if args.check:
        for path, expected in outputs.items():
            assert (ROOT/path).read_bytes() == expected, f'Stale generated artifact: {path}'
    else:
        for path, data in outputs.items():
            (ROOT/path).write_bytes(data)
        validate_outputs({path: (ROOT/path).read_bytes() for path in outputs})
    assert preserved_snapshot() == before, 'Existing static/typing source or assets changed'
    print(f'PASS: sleeping cat, 6 decoded opaque full 128x128 frames, shared palette, '
          f'index 0 unused, clear footer, infinite 3600 ms loop, {len(outputs[GIF_PATH])} bytes; '
          'embedded bytes match; deterministic; static/typing files unchanged.')


if __name__ == '__main__':
    main()
